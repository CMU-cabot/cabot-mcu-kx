"""Generate the firmware identity before each build (never reuse a stale header)."""
import json
import os
from pathlib import Path
import subprocess
import sys

HANDLE_DIR = Path(__file__).resolve().parents[1]


def resolve_version():
    override = os.environ.get("HANDLE_FIRMWARE_VERSION")
    if override is not None:
        version = override
    else:
        repo = HANDLE_DIR.parent
        def git(*args):
            return subprocess.check_output(
                ["git", "-c", f"safe.directory={repo}", "-C", str(repo), *args],
                text=True, stderr=subprocess.DEVNULL,
            ).strip()
        version = git("rev-parse", "--short=12", "HEAD")
        if git("status", "--porcelain", "--untracked-files=normal"):
            version += "-dirty"
    if not 1 <= len(version) <= 64 or any(not 33 <= ord(c) <= 126 for c in version):
        raise ValueError("HANDLE_FIRMWARE_VERSION must contain 1-64 printable ASCII characters without spaces")
    return version


if __name__ == "__main__":
    try:
        version = resolve_version()
    except (OSError, subprocess.CalledProcessError, ValueError) as exc:
        sys.exit(f"Cannot determine firmware identity: {exc}. Set HANDLE_FIRMWARE_VERSION explicitly (required in the Docker container).")
    if "--print" in sys.argv:
        print(version)
        sys.exit(0)
    (HANDLE_DIR / "firmware_version.h").write_text(
        "// Generated by tools/generate_version.py; do not edit.\n"
        "#pragma once\n#define HANDLE_FIRMWARE_VERSION " + json.dumps(version) + "\n"
    )
    print("Firmware version: " + version)
